#!/usr/bin/env python3
"""Build the moving latest mirror and honest immutable-release metadata index."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import shutil
import tempfile
from typing import Any

from build_canonical_public_status import ROOT, load_json
from build_tested_site_bundle import (
    bundle_lock, exchange_directories, file_rows, sync_directory, sync_stage, ordinary_path, tree_sha256,
)
from projection_files import ProjectionFiles


POLICY = ROOT / "status" / "versioned_release_policy.json"
STATUS_REL = Path("status/canonical-public-status.json")
INDEX_REL = Path("versions/index.json")


def build_index(status: dict[str, Any], policy: dict[str, Any]) -> dict[str, Any]:
    return {
        "schema_version": "asi_stack.versioned_release_index.v0",
        "latest": {
            "url": policy["latest_channel"]["url"],
            "source_commit": status["source_commit"],
            "status_id": status["status_id"],
            "mutable": "yes",
        },
        "immutable_storage_authority": policy["immutable_channel"]["storage_authority"],
        "releases": policy["known_releases"],
        "non_claims": policy["non_claims"],
    }


def root_rows(rows: list[dict]) -> list[dict]:
    return [row for row in rows if Path(row['path']).parts[0] not in {'latest', 'versions'}
            and Path(row['path']).name != '.DS_Store']


def channel_errors(site: Path, index: dict, rows: list[dict]) -> list[str]:
    errors = []
    if not (site / INDEX_REL).is_file() or load_json(site / INDEX_REL) != index:
        errors.append('versions/index.json differs from the current status and release policy')
    if not (site / 'latest').is_dir():
        errors.append('latest mirror is absent')
    elif file_rows(site / 'latest') != root_rows(rows):
        # Finder metadata is not part of either channel's content contract.
        mirror = [row for row in file_rows(site / 'latest') if Path(row['path']).name != '.DS_Store']
        if mirror != root_rows(rows):
            errors.append('latest mirror differs from the complete current root')
    return errors


def build_channels(site: Path, policy: dict, *, allow_local: bool, check: bool = False) -> dict:
    ordinary_path(site)
    if site.is_symlink() or not site.is_dir():
        raise ValueError('release channels require an ordinary rendered-site directory')
    site = site.resolve()
    # Inspect before reading status or copying: reject links and special files.
    before = file_rows(site)
    status = load_json(site / STATUS_REL)
    if not allow_local and (
        status.get('source_tree_state') != 'clean' or status.get('build_context') != 'tested_commit'
    ):
        raise ValueError('release-channel build requires canonical status from a clean tested commit')
    index = build_index(status, policy)
    if check:
        errors = channel_errors(site, index, before)
        if errors:
            raise ValueError('; '.join(errors))
        if file_rows(site) != before:
            raise ValueError('release channels changed during their read-only check')
        return index
    with bundle_lock(site):
        if file_rows(site) != before:
            raise ValueError('rendered source changed before acquiring the channel lease')
        # Never overwrite unknown content under the metadata-only versions channel.
        versions = site / 'versions'
        if versions.exists() and (
            not versions.is_dir() or {path.name for path in versions.iterdir()} != {'index.json'}
            or load_json(versions / 'index.json').get('schema_version') != 'asi_stack.versioned_release_index.v0'
        ):
            raise ValueError('refusing to replace an unrecognized versions directory')
        latest = site / 'latest'
        if latest.exists() and (not latest.is_dir() or not (latest / STATUS_REL).is_file()):
            raise ValueError('refusing to replace an unrecognized latest directory')
        if latest.exists():
            root_names = {row['path'] for row in root_rows(before)}
            extra = {row['path'] for row in file_rows(latest)
                     if Path(row['path']).name != '.DS_Store'} - root_names
            if extra:
                raise ValueError(f'refusing to discard unrecognized latest paths: {sorted(extra)[:8]}')
        if not channel_errors(site, index, before):
            # Do not replace identical generated bytes or churn their timestamps.
            return index
        container = Path(tempfile.mkdtemp(prefix='.asi-stack-release-channels-', dir=site.parent))
        stage = container / 'site'
        state = {'schema_version': 'asi_stack.release_channel_stage.v1', 'state': 'incomplete',
                 'destination': str(site), 'prior_tree_sha256': tree_sha256(before),
                 'support_state_effect': 'none', 'release_effect': 'none'}
        def record():
            ProjectionFiles().write(container / 'staging.json', json.dumps(state, indent=2) + '\n')
            sync_directory(container)
        record()
        attempted = installed = durable = False
        try:
            def omit_channels(directory, names):
                return {'latest', 'versions'} & set(names) if Path(directory) == site else set()
            # Preserve the complete root; create both channels outside the live tree.
            shutil.copytree(site, stage, symlinks=True, ignore=omit_channels)
            if root_rows(file_rows(stage)) != root_rows(before):
                raise ValueError('rendered source changed while staging release channels')
            shutil.copytree(stage, stage / 'latest', symlinks=True,
                            ignore=lambda directory, names: {'latest', '.DS_Store'} & set(names)
                            if Path(directory) == stage else {'.DS_Store'} & set(names))
            index_path = stage / INDEX_REL
            index_path.parent.mkdir()
            index_path.write_text(json.dumps(index, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
            staged_rows = file_rows(stage)
            errors = channel_errors(stage, index, staged_rows)
            if errors:
                raise ValueError('; '.join(errors))
            sync_stage(stage)
            state['state'] = 'prepared'; record()
            if file_rows(site) != before:
                raise ValueError('rendered source changed before release-channel installation')
            state['state'] = 'installation_attempted'; record()
            attempted = True
            exchange_directories(stage, site)
            installed = True
            if file_rows(stage) != before:
                raise ValueError('changed prior release-channel tree retained for inspection')
            if file_rows(site) != staged_rows:
                raise ValueError('installed release channels changed before acceptance')
            sync_directory(site.parent)
            durable = True
        finally:
            if attempted and not durable:
                state['state'] = ('installed_acceptance_or_durability_unconfirmed' if installed
                                  else 'installation_outcome_unconfirmed')
                record()
            else:
                shutil.rmtree(container)
    return index


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--site", type=Path, default=Path("_site"))
    parser.add_argument("--allow-local", action="store_true")
    parser.add_argument("--check", action="store_true", help="Verify channels without copying or changing any files")
    args = parser.parse_args()
    site = args.site if args.site.is_absolute() else ROOT / args.site
    policy = load_json(POLICY)
    try:
        index = build_channels(site, policy, allow_local=args.allow_local, check=args.check)
    except (ValueError, OSError) as error:
        raise SystemExit(f"Release-channel {'check' if args.check else 'build'} failed: {error}") from error
    print(
        f"{'Checked' if args.check else 'Built'} moving latest mirror for {index['latest']['source_commit'][:12]} and "
        f"immutable release index with {len(policy['known_releases'])} release row(s)."
    )


if __name__ == "__main__":
    main()
